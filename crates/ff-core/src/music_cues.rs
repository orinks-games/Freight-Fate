#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cues_are_sorted_and_well_formed() {
        for pair in CUES.windows(2) {
            assert!(
                pair[0].0 < pair[1].0,
                "CUES not strictly sorted at {} >= {}",
                pair[0].0,
                pair[1].0
            );
        }
        for &(key, lead, outro, end, intro, gain_db) in CUES {
            assert!((0.0..=2.0).contains(&lead), "{key}: bad lead {lead}");
            assert!(
                (lead..=end).contains(&outro),
                "{key}: bad outro {outro}..{end}"
            );
            assert!(end >= 0.5, "{key}: bad end {end}");
            assert!(intro >= 0.0, "{key}: bad intro {intro}");
            assert!(
                (-2.5..=2.5).contains(&gain_db),
                "{key}: bad gain_db {gain_db}"
            );
        }
    }

    #[test]
    fn lookup_accepts_bare_and_prefixed_keys() {
        let bare = track_cue("menu_theme").expect("menu_theme cue");
        let prefixed = track_cue("music/menu_theme").expect("prefixed cue");
        assert_eq!(bare, prefixed);
        assert!(bare.content_end_s > 120.0);
    }
}
