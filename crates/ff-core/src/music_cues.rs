//! Per-track acoustic cue points measured from the shipped `music.pak`
//! and classic music assets.
//!
//! Used by [`crate::music_playback`] to trigger menu crossfades and radio
//! segues right as a track winds down instead of waiting through trailing
//! silence, and to trim leading dead air and level loudness gently across
//! songs, host breaks, station IDs and commercials.

/// Acoustic cue points for one music or radio asset.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct TrackCue {
    /// Seconds of leading silence to skip when segueing into this track.
    pub lead_in_s: f32,
    /// Seconds from start where energy drops 10 dB below body loudness.
    pub outro_start_s: f32,
    /// Seconds from start where audible audio ends (before trailing silence).
    pub content_end_s: f32,
    /// Seconds from `lead_in_s` until the intro reaches body loudness.
    pub intro_ramp_s: f32,
    /// Gentle loudness trim in dB toward the pack median (-21.2 dBFS),
    /// clamped to `[-2.5, +2.5]` dB.
    pub gain_db: f32,
}

impl TrackCue {
    /// Natural fade-out tail length between `outro_start_s` and `content_end_s`.
    pub fn tail_s(self) -> f64 {
        f64::from((self.content_end_s - self.outro_start_s).max(0.0))
    }

    /// Linear gain multiplier corresponding to `gain_db`.
    pub fn linear_gain(self) -> f32 {
        10.0_f32.powf(self.gain_db / 20.0)
    }
}

/// Look up the measured acoustic cue for a shipped track key.
///
/// Accepts either bare keys (`"menu_theme"`) or `music/`-prefixed keys.
pub fn track_cue(key: &str) -> Option<TrackCue> {
    let bare = key.strip_prefix("music/").unwrap_or(key);
    let idx = CUES.binary_search_by_key(&bare, |(k, ..)| *k).ok()?;
    let (_, lead_in_s, outro_start_s, content_end_s, intro_ramp_s, gain_db) = CUES[idx];
    Some(TrackCue {
        lead_in_s,
        outro_start_s,
        content_end_s,
        intro_ramp_s,
        gain_db,
    })
}

