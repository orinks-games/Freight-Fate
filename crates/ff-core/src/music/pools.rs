/// Spoken host breaks are deliberately short, so they live outside the music
/// catalog but share the duration lookup for rotation timing.
pub static ALL_HOST_SEGMENTS: Lazy<Vec<MusicTrack>> = Lazy::new(|| {
    STATION_HOST_SEGMENTS
        .iter()
        .flat_map(|(_, pool)| pool.iter().cloned())
        .collect()
});

pub(super) static TRACKS_BY_KEY: Lazy<HashMap<String, MusicTrack>> = Lazy::new(|| {
    ALL_MUSIC_TRACKS
        .iter()
        .chain(ALL_HOST_SEGMENTS.iter())
        .map(|track| (track.key.clone(), track.clone()))
        .collect()
});
