fn host_pool(slug: &str) -> Vec<MusicTrack> {
    let (slug, station, description, durations) = HOST_TABLES
        .iter()
        .find(|(s, ..)| *s == slug)
        .expect("known host slug");
    host_segments(slug, station, description, durations)
}

pub static ROADHOUSE_HOST_SEGMENTS: Lazy<Vec<MusicTrack>> = Lazy::new(|| host_pool("roadhouse"));
pub static NIGHTLINE_HOST_SEGMENTS: Lazy<Vec<MusicTrack>> = Lazy::new(|| host_pool("nightline"));

/// The per-station host pools (`STATION_HOST_SEGMENTS`), in table order.
pub static STATION_HOST_SEGMENTS: Lazy<Vec<(String, Vec<MusicTrack>)>> = Lazy::new(|| {
    HOST_TABLES
        .iter()
        .map(|(slug, ..)| (slug.to_string(), host_pool(slug)))
        .collect()
});

/// The host pool for `host`, or an empty slice for a station with no voice.
pub fn station_host_segments(host: &str) -> &'static [MusicTrack] {
    STATION_HOST_SEGMENTS
        .iter()
        .find(|(slug, _)| slug == host)
        .map(|(_, pool)| pool.as_slice())
        .unwrap_or(&[])
}

/// The format pools (`STATION_PLAYLISTS`), in table order.
pub static STATION_PLAYLISTS: Lazy<Vec<(String, Vec<MusicTrack>)>> = Lazy::new(|| {
    let night: Vec<MusicTrack> = NIGHT_DRIVE_TRACKS
        .iter()
        .cloned()
        .chain(std::iter::once(NIGHT_JAZZ_TRACK.clone()))
        .chain(NIGHT_LINE_VOCAL_TRACKS.iter().cloned())
        .collect();
    vec![
        ("country".to_string(), COUNTRY_TRACKS.clone()),
        ("classic_rock".to_string(), CLASSIC_ROCK_TRACKS.clone()),
        ("blues".to_string(), BLUES_TRACKS.clone()),
        ("jazz".to_string(), JAZZ_TRACKS.clone()),
        ("night".to_string(), night),
        ("oldies".to_string(), OLDIES_TRACKS.clone()),
        ("gospel".to_string(), GOSPEL_TRACKS.clone()),
        ("tejano".to_string(), TEJANO_TRACKS.clone()),
        ("synthwave".to_string(), SYNTHWAVE_TRACKS.clone()),
    ]
});

/// The track pool for `playlist`, or an empty slice for an unknown one.
pub fn station_playlist(playlist: &str) -> &'static [MusicTrack] {
    STATION_PLAYLISTS
        .iter()
        .find(|(name, _)| name == playlist)
        .map(|(_, pool)| pool.as_slice())
        .unwrap_or(&[])
}

